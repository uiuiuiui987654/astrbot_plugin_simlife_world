"""Short writing cues for proactive messages, keyed off phrases in the state context.

The state context (``SmartContextInjector`` + life state) describes her body and
surroundings in plain words — "宿醉", "没吃早饭", "冬天"… Each ``StateHint`` turns a
recognised phrase into a reminder of how that state should colour the message.
"""

from __future__ import annotations

from dataclasses import dataclass

Markers = tuple[str, ...]


def _mentions(text: str, markers: Markers) -> bool:
    return any(marker in text for marker in markers)


@dataclass(frozen=True, slots=True)
class StateHint:
    """``gate`` must match before any case is tried; the first case whose marker groups all match wins."""

    name: str
    gate: Markers
    cases: tuple[tuple[tuple[Markers, ...], str], ...]

    @classmethod
    def simple(cls, name: str, markers: Markers, text: str) -> StateHint:
        return cls(name, markers, (((), text),))

    def pick(self, context: str) -> str:
        if self.gate and not _mentions(context, self.gate):
            return ""
        for groups, text in self.cases:
            if all(_mentions(context, group) for group in groups):
                return text
        return ""


